#!/usr/bin/env bash
# Regenerates Sources/OnePercent/EmbeddedEnglish.swift from the English strings — run after changing en.lproj.
# 2026-11-24 (#34): the English text is also built into the code, so OnePercent still shows text when its resource
# bundle cannot be found (instead of crashing). LocalizationTests fails when the two differ.
set -euo pipefail
cd "$(dirname "$0")/.."
plutil -convert json -o - Sources/OnePercent/Resources/en.lproj/Localizable.strings | python3 -c '
import json, sys
table = json.load(sys.stdin)
def literal(text):
    return "\"" + text.replace("\\", "\\\\").replace("\"", "\\\"").replace("\n", "\\n") + "\""
print("// Generated by scripts/embed-english.sh from Resources/en.lproj/Localizable.strings — do not edit by hand.")
print("// 2026-11-24 (#34): used only when the resource bundle cannot be found. LocalizationTests keeps it equal to the file.")
print("")
print("enum EmbeddedEnglish {")
print("    static let strings: [String: String] = [")
for key in sorted(table):
    print("        " + literal(key) + ": " + literal(table[key]) + ",")
print("    ]")
print("}")
' > Sources/OnePercent/EmbeddedEnglish.swift
echo "wrote Sources/OnePercent/EmbeddedEnglish.swift ($(grep -c '": "' Sources/OnePercent/EmbeddedEnglish.swift) strings)"
